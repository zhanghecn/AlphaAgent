import os

import numpy as np
import pandas as pd

pd.set_option("display.width", 340)
ROOT = "/root/project/ai/vnpy/量化因子研究/高位接力"
CSV = f"{ROOT}/全量明细.csv"
YEARS = ["2023", "2024", "2025", "2026"]

POINT_DEFS = [
    ("A1", "三接四阳", "修复启动格"),
    ("A2", "三接四阴", "老龙缩量格"),
    ("B1", "二接三阴", "竞价确认格"),
    ("B2", "二接三阳", "低开转强格"),
    ("B3", "三接四阳", "二波贴线格"),
]


def load():
    E = pd.read_csv(CSV)
    E["年"] = E["年"].astype(str)
    E["月"] = E["月"].astype(str)
    E["胜"] = E["次日收%"] > 0
    E["换手梯度"] = E["b2换手%"] - E["b1换手%"]

    # 地基/均线/反包扩展字段(第十九遍 relay_foundation.py 产出)
    ext = f"{ROOT}/地基均线反包明细.csv"
    if os.path.exists(ext):
        X = pd.read_csv(ext, dtype={"代码": str})
        keep = ["代码", "买入日", "地基档", "距MA10%", "站上均线数", "MA10位置",
                "反包结构", "断板天数", "前板高度", "反包收复%", "断板回撤%"]
        E = E.merge(X[keep], on=["代码", "买入日"], how="left")

    def tag(r):
        if r["四组"] == "三接四阳" and -15 <= r["距60日新高%"] < -8 \
                and r["均线"] not in ("+++", "-++", "+--") and r["前波60日最高板"] == 0:
            return "A1"
        if r["四组"] == "三接四阴" and r["前波120日最高板"] >= 3 and r["换手梯度"] < -5:
            return "A2"
        if r["四组"] == "二接三阴" and 6 <= r["b2开盘%"] < 9.5 and 0 <= r["换手梯度"] < 2:
            return "B1"
        if r["四组"] == "二接三阳" and -9 <= r["距60日新高%"] < -2 and r["b2开盘%"] < 0 \
                and 4 <= r["买入开盘%"] < 7:
            return "B2"
        fb_h = r.get("前板高度")
        ma10 = r.get("距MA10%")
        if r["四组"] == "三接四阳" and fb_h == fb_h and (fb_h or 0) >= 2 \
                and ma10 == ma10 and ma10 < 5:
            return "B3"
        return "—"

    E["方案点"] = E.apply(tag, axis=1)
    # 首刻标记: 开盘15分钟内首次触板(通达信15mK, 周期结束标签09:45)
    tf = f"{ROOT}/触板时间明细-全量.csv"
    if os.path.exists(tf):
        T = pd.read_csv(tf, dtype={"代码": str})
        mm = pd.to_datetime(T["触板时间"], format="%H:%M", errors="coerce")
        T["首刻"] = np.where(mm.isna(), "无数据",
                    np.where((mm.dt.hour * 60 + mm.dt.minute) <= 585, "首刻", "非首刻"))
        tmap = dict(zip(zip(T["代码"], T["买入日"]), T["首刻"]))
        E["首刻"] = [tmap.get((v, d), "无数据") for v, d in zip(E["代码"], E["买入日"])]
    else:
        E["首刻"] = "无数据"
    return E


def yearly_str(sub):
    by = sub.groupby("年")["持有到断板%"].agg(["size", "mean"])
    return " ".join(f"{y}:{float(by.loc[y,'mean']):+.2f}(n={int(by.loc[y,'size'])})"
                    for y in YEARS if y in by.index)


def fb_str(r):
    """反包结构列: 断X天·前Y板 / 无板 / 空。"""
    s = r.get("反包结构")
    if not s or s != s:
        return ""
    if s == "60日内无板":
        return "无板"
    h = r.get("前板高度")
    return f"{s}·前{int(h)}板" if h == h and h is not None else s


def ma10_str(r):
    v = r.get("距MA10%")
    return f"{v:+.1f}" if v == v and v is not None else ""


def miss_detail(r):
    """未命中票的归属判定: 对本组方案点逐条检查, 只列不满足的条件（人话）。
    命中票返回空（方案点列已是归属）。"""
    if r["方案点"] != "—":
        return ""
    g = r["四组"]
    grad = r["换手梯度"]
    out = []
    if g == "三接四阳":
        d = []
        if not (-15 <= r["距60日新高%"] < -8):
            d.append(f"距新高{r['距60日新高%']:.1f}%(要-15~-8)")
        if r["均线"] in ("+++", "-++", "+--"):
            d.append(f"均线{r['均线']}属整齐/纠缠")
        if r["前波60日最高板"] != 0:
            d.append(f"60日内有前波{r['前波60日最高板']}板")
        out.append("A1差[" + "/".join(d) + "]")
        d = []
        h = r.get("前板高度")
        if not (h == h and h is not None and h >= 2):
            d.append("60日内无≥2连板前波" if (h == h and h is not None) else "60日内无前板")
        m = r.get("距MA10%")
        if not (m == m and m is not None and m < 5):
            d.append(f"地基距10日线{m:+.1f}%(要<5)" if m == m else "距10日线缺数据")
        out.append("B3差[" + "/".join(d) + "]")
    elif g == "三接四阴":
        d = []
        if r["前波120日最高板"] < 3:
            d.append(f"120日前波最高{r['前波120日最高板']}板(要≥3)")
        if not (grad == grad and grad < -5):
            d.append(f"二板换手梯度{grad:+.1f}点(要<-5)" if grad == grad else "换手缺数据")
        out.append("A2差[" + "/".join(d) + "]")
    elif g == "二接三阴":
        d = []
        if not (6 <= r["b2开盘%"] < 9.5):
            d.append(f"二板开{r['b2开盘%']:+.1f}%(要6~9.5)")
        if not (grad == grad and 0 <= grad < 2):
            d.append(f"换手梯度{grad:+.1f}点(要0~2)" if grad == grad else "换手缺数据")
        out.append("B1差[" + "/".join(d) + "]")
    elif g == "二接三阳":
        d = []
        if not (-9 <= r["距60日新高%"] < -2):
            d.append(f"距新高{r['距60日新高%']:.1f}%(要-9~-2)")
        if not (r["b2开盘%"] < 0):
            d.append(f"二板开{r['b2开盘%']:+.1f}%(要低开)")
        if not (4 <= r["买入开盘%"] < 7):
            d.append(f"竞价{r['买入开盘%']:+.1f}%(要4~7)")
        out.append("B2差[" + "/".join(d) + "]")
    return "；".join(out)


def row_of(r):
    return (f"| {r['代码']} | {r['名称']} | {r['买入日']} | **{r['方案点']}** | {r.get('首刻','无数据')} | {r['结果']} "
            f"| {r['次日开%']:+.1f} | {r['次日收%']:+.1f} | {r['持有到断板%']:+.1f} "
            f"| {r['链']} | {r['买入开盘%']:+.1f} "
            f"| {r['阴阳']}{r['地基涨跌%']:+.1f} | {r['距60日新高%']:+.1f} | {r['均线']} "
            f"| {ma10_str(r)} | {fb_str(r)} "
            f"| {r['前波60日最高板'] or ''} | {r['昨日涨停家数'] or ''} | {miss_detail(r)} |")


def rewrite_monthly(E):
    out_root = f"{ROOT}/好差票验证"
    header = ("| 代码 | 名称 | 买入日 | 方案点 | 首刻 | 结果 | 次日开% | 次日收% | 持有到断板% | 链 | 买入开盘% | "
              "地基 | 位置% | 均线 | MA10% | 反包 | 前波 | 环境 | 不符合在哪 |")
    sep = "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"
    # 每组对应的方案点(一组可有多个点), 月度文件里只显示本组的点
    group_point = {
        "三接四阳": [("A1", "修复启动", "出手级",
                    "地基距60日新高8~15% × 均线不整齐 × 60日内首次连板"),
                   ("B3", "二波贴线", "观察级",
                    "60日内有过≥2连板（二波） × 地基收盘距10日线不到5%（贴线或下方）")],
        "三接四阴": [("A2", "老龙缩量", "出手级",
                    "近120日有过≥3连板 × 二板换手比首板低5点以上（竞价0~9.5%才打）")],
        "二接三阴": [("B1", "竞价确认", "观察级",
                    "二板高开6~9.5% × 换手只比首板多0~2点")],
        "二接三阳": [("B2", "低开转强", "观察级",
                    "地基距新高2~9% × 二板低开 × 竞价高开4~7%")],
    }
    for gname in ["二接三阴", "二接三阳", "三接四阴", "三接四阳"]:
        sub_all = E[E["四组"] == gname]
        gdir = f"{out_root}/{gname}"
        os.makedirs(gdir, exist_ok=True)
        pts = group_point[gname]
        for ym, sub in sub_all.groupby("月"):
            sub = sub.sort_values("买入日")
            done = sub[~sub["未完"]]
            hit = done[done["方案点"] != "—"]
            bad = done[done["坏票"]].sort_values("次日收%")
            good = done[~done["坏票"].fillna(False)].sort_values("持有到断板%", ascending=False)
            zb_bad = int(((done["结果"] == "炸板") & done["坏票"].fillna(False)).sum())
            fb = int((done["结果"] == "封次日负").sum())
            lb = int((done["结果"] == "连板").sum())
            if len(hit):
                parts = []
                for p, pname, _, _ in pts:
                    hp = hit[hit["方案点"] == p]
                    if len(hp):
                        parts.append(f"{p}（{pname}）{len(hp)}笔/胜率{(hp['胜'].mean())*100:.0f}%/"
                                     f"{hp['持有到断板%'].mean():+.2f}")
                hit_stat = (" | **命中 " + "；".join(parts) + "**") if parts else " | 本月无命中"
            else:
                hit_stat = " | 本月无命中"
            point_lines = [f"- **{p} {pname}（{plevel}）**：{pdef}" for p, pname, plevel, pdef in pts]
            L = [
                f"# 高位接力 · {gname} · {ym} · 好票坏票清单（方案点已标记）", "",
                f"本月触发 {len(done)} 笔 | 坏票 {len(bad)}（炸板没收回 {zb_bad} + 封住次日跌 {fb}） | "
                f"好票 {len(good)}（继续连板 {lb}） | 坏票率 {len(bad) / max(len(done), 1) * 100:.0f}%"
                + hit_stat
                + (f" | 数据末端未完 {len(sub) - len(done)} 笔不计" if len(sub) > len(done) else ""),
                "",
                f"**本组方案点（因子方案v1.3，买入前可知信息，命中才出手）**",
            ] + point_lines + [
                "- 「—」= 未命中本组方案点，方案不出手",
                "- 首刻列 = 开盘15分钟内首次触板（09:30~09:45）才算出手；非首刻=放弃；无数据=2024-08-15前无分钟存档", "",
                "**判定标准**",
                "- 买入 = 盘中碰到涨停价按涨停价买；一字板（全天没打开）买不进，已剔除",
                "- 坏票 = 买入后第二天收盘低于买价（炸板但第二天涨回来的算好票）",
                "- 持有到断板 = 涨停价买入，首次不再涨停的那天收盘卖出，15个交易日兜底", "",
                "**列说明**",
                "- 链 = 首板→买入前一天各板的「板型+开盘涨幅%」；板型分 一字 / 实体（下影<0.3%）/ 下影",
                "- 地基 = 首板前一天阴阳和涨跌幅；位置 = 首板前一天收盘距60日新高%；"
                "均线 = 首板前一天5/10/20/30日线排列（+=短线在上）",
                "- MA10% = 地基日收盘距10日线%；反包 = 首板前最近的板「断几天·前几板」（无板=60日内没有过涨停）",
                "- 前波 = 近60天内前一波连板最高几板；环境 = 前一天全市场涨停家数",
                "- 不符合在哪 = 未命中票对本组方案点的逐条判定，只列不满足的条件；命中票此列为空", "",
                f"## 坏票 — {len(bad)} 笔", "", header, sep,
            ]
            L += [row_of(r) for _, r in bad.iterrows()]
            L += ["", f"## 好票 — {len(good)} 笔", "", header, sep]
            L += [row_of(r) for _, r in good.iterrows()]
            with open(f"{gdir}/{ym}.md", "w", encoding="utf-8") as fp:
                fp.write("\n".join(L) + "\n")


