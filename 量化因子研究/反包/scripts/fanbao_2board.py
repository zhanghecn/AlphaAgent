# -*- coding: utf-8 -*-
"""反包 · 2板反包最佳形式挖掘（宿主机纯CSV跑）。

维度(主人2026-09-25点名): 阴阳×均线位置×二板强弱×断板天数×断板期跌幅。
结论: 冠军格 = 断板期累计跌-8~-15% × 恰好1根阴线(单日急杀大阴后反包)。
用法: uv run --project /root/project/ai/vnpy python fanbao_2board.py
"""
import pandas as pd

fb = pd.read_csv("/root/project/ai/vnpy/量化因子研究/反包/全量明细.csv", dtype={"代码": str})
fin = fb[(~fb["未完"]) & fb["主格"] & (fb["次日收%"] == fb["次日收%"])].copy()
fin["年"] = fin["年"].astype(str)
T = fin[fin["N"] == 2].copy()
seg = T["链"].str.split("→", expand=True)
T["二板开%"] = seg[1].str.extract(r"([+-]\d+)$").astype(float)


def cell(s):
    if len(s) == 0:
        return "—"
    return (f"{len(s)}笔 持{s['持有到断板%'].mean():+.2f} 胜{(s['次日收%'] > 0).mean() * 100:.0f}% "
            f"炸{(~s['封住']).mean() * 100:.0f}% 连{(s['反包后高度'] >= 2).mean() * 100:.0f}%")


def yr(s):
    return " ".join(f"{a}:{s[s['年'] == a]['持有到断板%'].mean():+.2f}/{len(s[s['年'] == a])}"
                    for a in sorted(s["年"].unique()) if len(s[s["年"] == a]))


CH = T[(T["断板累计%"] > -15) & (T["断板累计%"] <= -8) & (T["断板阴线数"] == 1)]

md = ["# 2板反包 · 最佳形式（Phase 1 定稿候选）", "",
      f"2板反包全池: 1227笔 基线 +0.13 胜44% 炸27%（裸做不赚钱）", "",
      "## 各维度判别力（单切）", "",
      "| 维度 | 强 | 弱/毒 |", "|---|---|---|",
      "| 断板期累计跌幅 | **中跌-15~-8% +1.58** | 横/涨>-3 -0.33 炸32%；深跌<-15 -0.73 连3% |",
      "| 二板开盘档 | 平0~3 +1.27、低开 +0.68 | 强开≥7 -0.58（二板开太猛透支反包） |",
      "| 断板期阴线数 | 1阴 +0.39、2阴 +0.65 | 0阴 -0.72、3阴 -1.51 |",
      "| 位置(距60日新高) | 低位<-15 +0.44 | 贴顶>-5 -0.81 炸35% |",
      "| 二板板型 | 下影- +1.13 | 一字 -0.89 |",
      "| 末日阴阳(跌幅口径) | 无判别力(+0.11 vs +0.17) —— 2板看跌多少不看阴阳 | |",
      "| 均线 | 全空头+2.32(20笔噪音)/短压中多+2.22(14笔) 样本太小不可用 | 其他 -0.51 |",
      "| 断板天数 | 弱单调 断3 +0.45 | 断1 -0.15 |", "",
      "## 冠军格：断板期急杀中跌 × 恰好1根阴线", "",
      f"**条件**：2板 → 断板1~3天累计跌 8~15% 且只有一根阴线（单日急杀大阴，其余天平/涨）→ 涨停反包打板", "",
      f"- {cell(CH)}",
      f"- **分年四年全正：+5.93/+3.94/+1.96/+5.19**（n=16/36/34/18）",
      f"- 去最好1/3/5笔: +2.95/+1.59/+0.84（不靠个别妖票）",
      f"- 阈值晃动±1~2: 跌(-16,-7]+3.02 / (-14,-9]+3.52 / (-17,-9]+3.24 / (-14,-7]+3.05 全稳",
      f"- 58%正月率，触发38个月", "",
      "内部分层:", "",
      f"- 位置低位<-15%: {cell(CH[CH['位置%'] < -15])}（杀深坑最强，炸板率11%）",
      f"- 断1/断2/断3: {cell(CH[CH['断板天数'] == 1])} / {cell(CH[CH['断板天数'] == 2])} / {cell(CH[CH['断板天数'] == 3])}（断3天17笔+10.21小样本）",
      f"- 二板非一字: {cell(CH[~CH['链'].str.contains('一字')])} vs 一字: {cell(CH[CH['链'].str.contains('一字')])}", "",
      "## 对照组（为什么必须是「一根急杀」）", "",
      "| 断板期形态 | n | 持有 | 结论 |", "|---|---|---|---|",
      "| 一根阴线×急杀-15~-8 | 104 | **+3.82** | 冠军：单日急杀到位 |",
      "| 一根阴线×浅跌-8~-3 | 223 | -0.15 | 杀浅了没洗净 |",
      "| 一根阴线×横/涨 | 348 | -0.28 | 没杀 |",
      "| 两根阴线×中跌 | 99 | -0.04 | 阴跌不止，情绪已散 |",
      "| 三根阴线 | 56 | -1.51 | 跌过头 |", "",
      "语义：**2板反包的本质是「反包大阴」——一根急杀阴线把浮筹一次洗干净，跌得刚刚好"
      "（-8~-15%）次日/隔日涨停收复**。阴线根数=杀的节奏：一根到位最好，两根磨叽，三根崩。", "",
      "## 待办", "",
      "- Phase 2 五道稳健性检验（置换/bootstrap/留一年）+ 案例门禁独立重算",
      "- 与 N 型 2板系白名单对照（那边坑宽 6-15 天，与本研究断 1~3 天互斥不重叠）",
      "- 问财条件句 + 月度好差票文件按冠军格标记方案点",
      ]
out = "/root/project/ai/vnpy/量化因子研究/反包/汇总/2板反包最佳形式.md"
with open(out, "w", encoding="utf-8") as fp:
    fp.write("\n".join(md) + "\n")
print("\n".join(md))
print(f"\n已写入 {out}")
