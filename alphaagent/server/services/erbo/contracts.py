def tag_point(last_open_pct: float | None) -> str:
    """末日开盘方式打档;死格返回 —。"""
    if last_open_pct is None:
        return "—"
    if OPEN_A_LO <= last_open_pct <= OPEN_A_HI:
        return "A"
    if last_open_pct <= OPEN_B_MAX:
        return "B"
    return "—"


def dead_open_reason(last_open_pct: float | None) -> str:
    """死格文案(命中的票=雷达,不出手)。"""
    if last_open_pct is None:
        return ""
    if OPEN_B_MAX < last_open_pct < OPEN_A_LO:
        return "末日浅低开(-4~-2):还在阴跌不干脆(23笔+0.17炸30%分年两负)"
    if last_open_pct > OPEN_A_HI:
        return "末日高开(>+2):急着出货的假动作(5笔-2.99胜20%)"
    return ""


def is_cold_market(mkt_lim_prev: float | None) -> bool:
    """情绪冰点警示(减半仓,不剔除)。"""
    return mkt_lim_prev is not None and mkt_lim_prev < MKT_COLD_TH


