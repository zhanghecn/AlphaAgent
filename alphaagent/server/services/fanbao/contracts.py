def seg_of(n_board: int) -> str | None:
    """高度段归属;3板返回 None(不进池,仅回测参考行)。"""
    if n_board == 2:
        return "2板"
    if n_board == 4:
        return "4板"
    if n_board >= 5:
        return "5+板"
    return None


def tag_point(n_board: int, gap: int, yin_yang: str, break_drop_pct: float,
              break_yin_count: int, last_entity: str | None = None,
              last_open_pct: float | None = None) -> str:
    """五方案点标记(v2.1 与产品回测同逻辑;五点互斥,单值)。

    break_drop_pct 断板累计%(今日收盘/末板收盘-1);break_yin_count 断板期
    实体阴线数(收盘<开盘);last_entity 末日实体阴/阳;last_open_pct 末日开盘%。"""
    if (n_board == 2 and gap in GS_MAIN
            and S1_DROP_LO < break_drop_pct <= S1_DROP_HI
            and break_yin_count == S1_YIN_EXACT
            and last_open_pct is not None and last_open_pct <= S1_LAST_OPEN_MAX):
        return "S1"
    if (n_board == 4 and yin_yang == "阴" and gap == 1
            and last_entity == "阴"
            and last_open_pct is not None and last_open_pct > S2_OPEN_LO):
        return "S2"
    if n_board >= 5 and yin_yang == "阳" and gap == 1:
        return "S3"
    if n_board >= 5 and yin_yang == "阴" and gap == 1:
        return "O1"
    if n_board == 4 and yin_yang == "阴" and gap == 3:
        return "O2"
    return "—"


def is_high_var_open(last_open_pct: float | None) -> bool:
    """S2 顶格开警示(开>7% 胜率五五开,减半仓;不剔除)。"""
    return last_open_pct is not None and last_open_pct > S2_TOPGAP_TH


def dead_cell_reason(n_board: int, gap: int, yin_yang: str,
                     break_yin_count: int, break_drop_pct: float) -> str:
    """六组主格内的死格(命中也不买);3板与断4+不进池不在此列。

    O2 覆盖整个 4板阴断3 格(观察级),不标死格。"""
    if n_board == 4 and yin_yang == "阳":
        return "4板阳全系:没跌横着=假强势暗中出货(断1 -1.09)"
    if n_board >= 5 and yin_yang == "阳" and gap == 3:
        return "5+阳断3:-4.71 炸56%,扛过头"
    if n_board >= 4 and gap in (2, 3) and not (n_board == 4 and yin_yang == "阴" and gap == 3):
        return "4+断2~3天:情绪延续与充分洗盘之间的尴尬中间态"
    if n_board == 2:
        if break_yin_count <= 0:
            return "2板0阴:断板期没洗盘"
        if break_yin_count >= YIN_DEAD_MIN:
            return "2板3阴+:磨没了起不来(-1.51)"
        if break_drop_pct < DEEP_DROP_TH:
            return "2板深跌超15%:跌过头起不来"
    return ""


